import { describe, expect, it } from 'vitest';
import { 查找社交NPC索引 } from '../hooks/useGame/variableModelWorkflow';

// 复现玩家反馈：生成商人类 NPC 时档案被误写入女一（社交[0]）。
// 女一（主要角色）的简介/身份可能包含“商号/丝绸/掌柜”等词，
// 匹配逻辑必须严禁“发送者包含身份片段”的反向命中，否则会把新商人误判为女一。
describe('查找社交NPC索引 —— 主要角色（女一等）匹配方向', () => {
    const 女一 = { 姓名: '苏婉儿', 身份: '明月圣女', 简介: '经营丝绸商号的掌柜之女', 是否主要角色: true };
    const 普通商人 = { 姓名: '钱通', 身份: '丝绸商号掌柜', 简介: '城西布庄老板', 是否主要角色: false };

    it('反向包含（发送者包含身份片段）不得命中主要角色 —— 修复前此用例会把商人误判为女一', () => {
        const social = [女一];
        // 发送者“丝绸商号掌柜”包含女一简介里的片段“丝绸商号”，但方向反了，必须不命中女一
        expect(查找社交NPC索引(social, '丝绸商号掌柜')).toBe(-1);
    });

    it('正向包含（身份包含发送者）应命中主要角色', () => {
        const social = [{ 姓名: '苏婉儿', 身份: '明月圣女', 简介: '圣女座下弟子', 是否主要角色: true }];
        expect(查找社交NPC索引(social, '圣女')).toBe(0);
    });

    it('精确相等（身份恰为发送者）应命中主要角色', () => {
        const social = [{ 姓名: '苏婉儿', 身份: '丝绸商号掌柜', 简介: '女掌柜', 是否主要角色: true }];
        expect(查找社交NPC索引(social, '丝绸商号掌柜')).toBe(0);
    });

    it('主要角色姓名精确匹配优先于非主要角色的模糊包含', () => {
        const social = [
            { 姓名: '苏婉儿', 身份: '明月圣女', 简介: '圣女', 是否主要角色: true },
            // 非主要角色简介“苏婉儿的侍女”双向包含“苏婉儿”，但不能抢在女一精确姓名之前
            { 姓名: '小翠', 身份: '丫鬟', 简介: '苏婉儿的侍女', 是否主要角色: false }
        ];
        expect(查找社交NPC索引(social, '苏婉儿')).toBe(0);
    });

    it('发送者与主要角色无关、但与非主要角色双向匹配时，命中非主要角色', () => {
        const social = [女一, 普通商人];
        expect(查找社交NPC索引(social, '丝绸商号掌柜')).toBe(1);
    });

    it('完全无关发送者返回 -1，提示需新建 NPC', () => {
        const social = [女一, 普通商人];
        expect(查找社交NPC索引(social, '陌生剑客')).toBe(-1);
    });
});
