import { describe, expect, it } from 'vitest';
import {
    清洗描述文本,
    构建物品视觉描述,
    物品主体需要AI重写,
    移除制作者前缀
} from '../services/ai/itemImageGeneration';

describe('物品生图提示词清洗（防止装备简介原样进 prompt）', () => {
    it('剔除“能遮挡小雨，提供微弱的身体防护”这类效果从句，只留外观', () => {
        const cleaned = 清洗描述文本('李方文用野麻叶和粗麻绳穿扎固定而成的简易披风，能遮挡小雨，提供微弱的身体防护。');

        expect(cleaned).not.toContain('能遮挡小雨');
        expect(cleaned).not.toContain('提供微弱的身体防护');
        expect(cleaned).toContain('简易披风');
        expect(cleaned).toContain('野麻叶');
        expect(cleaned).toContain('粗麻绳');
    });

    it('剥离“李方文用……制成的”里的人名前缀', () => {
        expect(移除制作者前缀('李方文用野麻叶和粗麻绳穿扎固定而成的简易披风'))
            .toBe('用野麻叶和粗麻绳穿扎固定而成的简易披风');
    });

    it('不误删“青钢剑用玄铁打造而成”里的物品名', () => {
        expect(移除制作者前缀('青钢剑用玄铁打造而成')).toBe('青钢剑用玄铁打造而成');
    });

    it('保留“可折叠”“会发光”这类纯外观从句', () => {
        expect(清洗描述文本('一顶可折叠的竹编斗笠，会泛出淡淡灵光。')).toContain('可折叠的竹编斗笠');
        expect(清洗描述文本('一顶可折叠的竹编斗笠，会泛出淡淡灵光。')).toContain('会泛出淡淡灵光');
    });

    it('数值/机制文案整段不进入视觉描述', () => {
        expect(构建物品视觉描述({
            名称: '临时奖励牌',
            描述: '生命值恢复 +10，技能冷却减少 1 回合。'
        })).toBe('');
    });

    it('普通外观描述仍然完整保留', () => {
        expect(构建物品视觉描述({
            名称: '斑驳旧木盒',
            描述: '一只边角磨损的旧木盒，铜扣泛着暗沉光泽。'
        })).toContain('一只边角磨损的旧木盒');
    });

    it('中文视觉描述一律判定需要 AI 重写，不再被当成强主体', () => {
        const 蓑衣 = {
            名称: '简易披风',
            类型: '防具',
            品质: '凡品',
            描述: '李方文用野麻叶和粗麻绳穿扎固定而成的简易披风，能遮挡小雨，提供微弱的身体防护。'
        };
        // 旧逻辑：命中“柔性服装”类目即判为强主体，中文简介被原样塞进 prompt。
        expect(物品主体需要AI重写({ ...蓑衣, 视觉描述: 蓑衣.描述 })).toBe(true);
    });

    it('英文视觉描述不需要重写', () => {
        expect(物品主体需要AI重写({
            名称: 'Some Gadget',
            类型: '杂物',
            视觉描述: 'a small round metal device with a glass lens'
        })).toBe(false);
    });
});
